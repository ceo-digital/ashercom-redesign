(function () {
  const EN = window.ASHER_EN;
  const KEY = "asher-home-lang";
  const heTitle = document.title;
  const heDesc = document.querySelector('meta[name="description"]');
  const heDescContent = heDesc ? heDesc.getAttribute("content") : "";

  function currentLang() {
    return localStorage.getItem(KEY) === "en" ? "en" : "he";
  }

  function setText(el, value, html) {
    if (value == null) return;
    if (html) el.innerHTML = value;
    else el.textContent = value;
  }

  function apply(lang) {
    const html = document.documentElement;
    html.lang = lang === "en" ? "en" : "he";
    html.dir = lang === "en" ? "ltr" : "rtl";
    document.body.setAttribute("data-lang", lang);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const htmlMode = el.hasAttribute("data-i18n-html");
      if (!el.dataset.i18nHe) el.dataset.i18nHe = htmlMode ? el.innerHTML : el.textContent.trim();
      const key = el.getAttribute("data-i18n");
      setText(el, lang === "en" ? EN[key] : el.dataset.i18nHe, htmlMode);
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      if (!el.dataset.i18nAriaHe) el.dataset.i18nAriaHe = el.getAttribute("aria-label") || "";
      const key = el.getAttribute("data-i18n-aria");
      el.setAttribute("aria-label", lang === "en" ? (EN[key] || el.dataset.i18nAriaHe) : el.dataset.i18nAriaHe);
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
      if (!el.dataset.i18nAltHe) el.dataset.i18nAltHe = el.getAttribute("alt") || "";
      const key = el.getAttribute("data-i18n-alt");
      el.setAttribute("alt", lang === "en" ? (EN[key] || el.dataset.i18nAltHe) : el.dataset.i18nAltHe);
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      if (!el.dataset.i18nPhHe) el.dataset.i18nPhHe = el.getAttribute("placeholder") || "";
      const key = el.getAttribute("data-i18n-placeholder");
      el.setAttribute("placeholder", lang === "en" ? (EN[key] || el.dataset.i18nPhHe) : el.dataset.i18nPhHe);
    });

    document.title = lang === "en" ? EN["meta.title"] : heTitle;
    if (heDesc) heDesc.setAttribute("content", lang === "en" ? EN["meta.description"] : heDescContent);

    const toggle = document.querySelector(".lang-toggle");
    if (toggle) {
      toggle.textContent = lang === "en" ? EN["lang.toHe"] : EN["lang.toEn"];
      toggle.setAttribute("aria-label", lang === "en" ? EN["lang.ariaHe"] : EN["lang.ariaEn"]);
      toggle.setAttribute("aria-pressed", lang === "en" ? "true" : "false");
    }

    localStorage.setItem(KEY, lang);
  }

  window.asherI18nText = function (key) {
    return currentLang() === "en" ? (EN[key] || "") : "";
  };

  window.asherSetLang = apply;

  document.addEventListener("click", (e) => {
    const btn = e.target.closest(".lang-toggle");
    if (!btn) return;
    apply(currentLang() === "en" ? "he" : "en");
  });

  apply(currentLang());
})();
